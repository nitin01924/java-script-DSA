const first = 10;
const second = 3;

console.log('Addition:', first + second);
console.log('Remainder:', first % second);
console.log('Greater than:', first > second);
console.log('Strict equality:', first === second);
console.log('Both conditions:', first > 0 && second > 0);

// % is useful for checking even numbers: number % 2 === 0.
// Time: O(1), Space: O(1) because every operation uses fixed-size values.
